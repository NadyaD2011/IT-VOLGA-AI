"""Формат государственных регистрационных знаков РФ (ГОСТ Р 50577-2018).

Всё здесь синхронизировано с валидатором/эвалуатором организаторов
(Волга-IT 2026, полуфинал «ИИ и анализ данных»):

  type1, type1a : [Л][Ц][Ц][Ц][Л][Л][код региона 2-3 цифры]   напр. A123BC777
  type1b        : [Л][Л][Ц][Ц][Ц][код региона 2-3 цифры]      напр. AB12377
  other         : произвольная строка A-Z0-9# длиной до 12 (или пусто)

Буквы — только латиница, совпадающая по начертанию с кириллицей:
A B E K M H O P C T Y X. Нечитаемые позиции — «#».
"""
from __future__ import annotations

import re

LETTERS = "ABEKMHOPCTYX"
DIGITS = "0123456789"
PLATE_CHARS = LETTERS + DIGITS
UNKNOWN = "#"

# Кириллица -> латиница ровно так же, как в скриптах организаторов.
CYR_LETTERS = "АВЕКМНОРСТУХ"
CYR_TO_LAT = str.maketrans(CYR_LETTERS + CYR_LETTERS.lower(), LETTERS + LETTERS)

_L = f"[{LETTERS}{UNKNOWN}]"
_D = f"[0-9{UNKNOWN}]"
_REGION = f"{_D}{{2,3}}"

# Маски совпадают с PLATE_MASKS в validate_dataset.py / evaluate.py.
MASKS = {
    "type1": re.compile(f"^{_L}{_D}{{3}}{_L}{{2}}{_REGION}$"),
    "type1a": re.compile(f"^{_L}{_D}{{3}}{_L}{{2}}{_REGION}$"),
    "type1b": re.compile(f"^{_L}{{2}}{_D}{{3}}{_REGION}$"),
    "other": re.compile(r"^[A-Z0-9#]{0,12}$"),
}

# Длина «тела» номера без кода региона (чтобы отделять регион).
BODY_LEN = {"type1": 6, "type1a": 6, "type1b": 5}

PLATE_TYPES = ("type1", "type1a", "type1b", "other")
TARGET_TYPES = ("type1", "type1a", "type1b")

# Порядок классов в labels/*.txt (раздел 6.2 задания).
CLASS_OF_TYPE = {"type1": 0, "type1a": 1, "type1b": 2, "other": 3}
TYPE_OF_CLASS = {v: k for k, v in CLASS_OF_TYPE.items()}


def position_kinds(plate_type: str):
    """Список допустимых алфавитов по позициям ('L'/'D'/'?').

    Для type1a это «склеенная» строка из двух строк знака, поэтому
    позиции идентичны type1. Для other ограничений нет ('?').
    """
    if plate_type in ("type1", "type1a"):
        return ["L", "D", "D", "D", "L", "L", "D", "D", "D"]
    if plate_type == "type1b":
        return ["L", "L", "D", "D", "D", "D", "D", "D"]
    return ["?"] * 12


# Омофоны, используемые только для «починки» номера, не влезшего в маску.
# Цифра -> похожая буква и обратно (символы, реально путаемые OCR на ГРЗ).
DIGIT_TO_LETTER = {
    "0": "O", "8": "B", "6": "C", "9": "P", "3": "E", "4": "A",
    "7": "T", "5": "S", "1": None, "2": None,
}
LETTER_TO_DIGIT = {
    "O": "0", "B": "8", "C": "6", "P": "9", "E": "3", "A": "4", "T": "7", "S": "5",
    "K": None, "M": None, "H": None, "X": "X", "Y": "Y",
}


def normalize(text: str) -> str:
    """Верхний регистр, кириллица -> латиница, удаление пробелов/дефисов
    и символов вне алфавита ГРЗ (кроме «#»)."""
    t = (text or "").strip().upper().translate(CYR_TO_LAT)
    t = re.sub(r"[^A-Z0-9#]", "", t)
    # Латинские буквы вне допустимого набора оставляем как есть — они
    # допустимы для other; для целевых типов решит repair()/mask.
    return t


def fits_mask(plate: str, plate_type: str) -> bool:
    rx = MASKS.get(plate_type)
    return bool(rx and rx.fullmatch(plate or ""))


def region_of(plate: str, plate_type: str) -> str:
    body = BODY_LEN.get(plate_type)
    if body is None or len(plate) <= body:
        return ""
    return plate[body:]


def is_region_plausible(region: str) -> bool:
    """Мягкая проверка кода региона (используется только для починки, не для отказа).

    Валидатор из задания запрещает лишь «000»-подобные коды; правило
    «трёхзначный код начинается с 1, 2 или 7» устарело (выдаются 323, 550, 252...).
    """
    if len(region) == 2:
        return region != "00"
    if len(region) == 3:
        if region == "000" or region[0] == "0":
            return False
        if "#" in region:
            return True
        return 1 <= int(region[1:]) <= 99
    return len(region) == 0


def _edit_to_mask(plate: str, plate_type: str) -> str:
    """Пытается минимальными заменами похожих символов привести номер к маске.

    Возвращает исправленную строку или None, если починка не удалась.
    Никаких «догадок» о читаемости не добавляет: меняет только символы,
    стоящие не на своём месте (буква в позиции цифры и наоборот).
    """
    kinds = position_kinds(plate_type)
    body = BODY_LEN.get(plate_type)
    if body is None:
        return plate if fits_mask(plate, plate_type) else None

    # Длина: допустимы body+2 или body+3; если на 1 короче/длиннее — пробуем
    # достречь/обрезаем регион (типичная ошибка: регион прочитан как 1 или 4 цифры).
    if len(plate) not in (body + 2, body + 3) and UNKNOWN not in plate:
        core, tail = plate[:body], plate[body:]
        digits = re.sub(r"[^0-9]", "", tail)
        if len(digits) >= 2:
            plate = core + digits[:3]
        elif len(core + digits) in (body + 2, body + 3):
            plate = core + digits
        else:
            return None

    out = list(plate)
    for i, ch in enumerate(out):
        kind = kinds[i] if i < len(kinds) else "?"
        if kind == "?":
            continue
        if kind == "L" and ch in DIGITS:
            out[i] = DIGIT_TO_LETTER.get(ch) or "#"
        elif kind == "D" and ch not in DIGITS and ch != UNKNOWN:
            out[i] = LETTER_TO_DIGIT.get(ch) or "#"
    fixed = "".join(out)
    return fixed if fits_mask(fixed, plate_type) else None


def repair(plate: str, plate_type: str):
    """Нормализация + починка под маску. Возвращает (plate, ok).

    ok=False — привести к маске выбранного типа не удалось; вызывающий код
    обычно понижает тип до other и отдаёт строку как есть (для other маска
    мягкая).
    """
    plate = normalize(plate)
    if plate_type == "other":
        return (plate if MASKS["other"].fullmatch(plate) else "")[:12], True
    if fits_mask(plate, plate_type):
        return plate, True
    fixed = _edit_to_mask(plate, plate_type)
    if fixed is not None:
        return fixed, True
    return plate, False


def fits_any_target(plate: str):
    """Первый целевой тип, под маску которого подходит строка (или None)."""
    for t in TARGET_TYPES:
        if fits_mask(plate, t):
            return t
    return None


def random_plate(rng, plate_type: str) -> str:
    """Случайный «правдоподобный» номер — используется генератором синтетики."""
    L, D = LETTERS, DIGITS
    region = str(rng.choice(REGION_CODES))

    def letters(n=2):
        return "".join(rng.choice(L) for _ in range(n))

    def digits(n):
        return "".join(rng.choice(D) for _ in range(n))

    if plate_type == "type1b":
        return letters(2) + digits(3) + region
    # type1 / type1a
    return letters(1) + digits(3) + letters(2) + region


